//! The native side of the taskbar's shared hover system (`hoverPanel.ts`).
//!
//! The webview's hover popups (app previews, the media hover card) persist
//! on the belief that the cursor still hovers them. That belief is fed by
//! DOM pointer events — which the webview stops receiving the moment this
//! loop toggles the overlay click-through, i.e. the instant the cursor
//! steps off every hit-testable region (a button, an open popup, an open
//! menu). A pending `pointerleave` can then simply never be delivered, and
//! the webview is left holding a "still hovering" state with the cursor
//! long gone: the popup parks itself open.
//!
//! `supervise` (called every tick, right after the click-through decision)
//! emits the one authoritative exit signal: on the transition from "the
//! cursor was in some hit-testable region" to "it is in none", one
//! `hover-blur` event. The shared webview hover system treats that exactly
//! like its own leave — it arms the close grace, which a re-entered popup
//! (or source) cancels again. It also resets the preview popup's own mouse
//! latch, which can go stale when Windows moved the popup under a parked
//! cursor (`WM_MOUSELEAVE` is only generated by mouse input, never by a
//! window moving away).

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

/// The app handle, set once at boot (the hit-test loop thread has no Tauri
/// handle itself; `self::shell` only receives the webview window).
static APP: OnceLock<tauri::AppHandle> = OnceLock::new();
/// Seen per hover session: the cursor was in a hit-testable region — so
/// the webview's popups could observe it too. The first blind tick
/// afterwards is where their DOM-level hover beliefs can be stale.
static SIGHTED: AtomicBool = AtomicBool::new(false);

pub fn set_app(app: tauri::AppHandle) {
    let _ = APP.set(app);
}

/// One authoritative `hover-blur` per interactive → blind crossing (see the
/// module comment). Fires with an open-or-not popup alike: the webview's
/// hover system no-ops for closed panels, and subscribers register only
/// while theirs is open.
pub fn supervise(interactive: bool) {
    if interactive {
        SIGHTED.store(true, Ordering::Relaxed);
        return;
    }
    if !SIGHTED.swap(false, Ordering::Relaxed) {
        return;
    }
    // The preview popup cannot be under the cursor in a blind tick, so a
    // still-true latch is stale; clear it silently — the blur below is the
    // webview-facing signal for the same crossing.
    crate::shell::preview::reset_hover_latch();
    if let Some(app) = APP.get() {
        use tauri::Emitter;
        let _ = app.emit("hover-blur", true);
    }
}
